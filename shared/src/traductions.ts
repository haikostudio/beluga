/** Le rang de chaque langue dans le quadruplet `[en, es, de, zh]`. */
const RANG: Record<Exclude<LangueId, 'fr'>, 0 | 1 | 2 | 3> = { en: 0, es: 1, de: 2, zh: 3 };

function dictionnaireDe(langue: Exclude<LangueId, 'fr'>): Dictionnaire {
  const rang = RANG[langue];
  const table: Record<string, string> = {};
  for (const [francais, quatre] of Object.entries(TEXTES)) {
    const traduction = quatre[rang];
    if (traduction) table[francais] = traduction;
  }
  return table;
}

