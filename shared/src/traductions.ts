/**
 * LE DICTIONNAIRE DE L'INTERFACE — cinq langues, une seule table.
 *
 * LA CLÉ EST LE TEXTE FRANÇAIS, écrit tel qu'il apparaît dans l'écran. Ce choix
 * est expliqué dans `shared/src/traduire.ts` : il rend la panne impossible, une
 * traduction manquante retombant sur du français lisible plutôt que sur un vide
 * ou un nom de clé nu.
 *
 * LES QUATRE TRADUCTIONS SONT CÔTE À CÔTE, dans l'ordre `[en, es, de, zh]` :
 * une langue oubliée se voit à l'œil dans la ligne, et le type ne laisse pas
 * écrire trois valeurs au lieu de quatre. Quatre blocs séparés auraient obligé
 * à recopier chaque phrase française quatre fois, et une langue aurait dérivé
 * des autres sans que rien ne le dise.
 *
 * LES TROUS `{ainsi}` SE RETROUVENT DANS CHAQUE TRADUCTION, mais pas forcément
 * à la même place : c'est tout l'intérêt de traduire la phrase ENTIÈRE plutôt
 * que des morceaux collés. `scripts/verif-langues.mjs` refuse un trou perdu en
 * route.
 *
 * CE QUI N'EST PAS ICI, ET NE DOIT PAS Y ÊTRE : tout ce que les AGENTS
 * produisent — leurs réponses, les titres et descriptions de cartes, la mémoire
 * du projet, les documents. Ce sont des matières de travail, et les traduire les
 * dénaturerait. Les NOMS PROPRES non plus : « Claude », « Codex », « Cursor »,
 * « GitHub », « HaikoDev », « CHF » s'écrivent pareil partout.
 */

